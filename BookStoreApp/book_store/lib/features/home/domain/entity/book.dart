class Book {
  final String title;
  final String author;
  final String image;
  final String price;
  final String publisher;
  final String pages;
  final String genre;

  Book({
    required this.title,
    required this.author,
    required this.image,
    required this.price,
    required this.publisher,
    required this.pages,
    required this.genre,
  });
}
